/* global DOMParser, XMLSerializer, document, Image */

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import puppeteer from "puppeteer-core";

const source = await readFile("assets/branding/ui-torture-lab.svg", "utf8");
const lightSource = await readFile("assets/branding/ui-torture-lab-light.svg", "utf8");
const browser = await puppeteer.launch({ executablePath: await puppeteer.executablePath("chrome"), headless: true });
let assets;
try {
  const page = await browser.newPage();
  assets = await page.evaluate(async ({ source, lightSource }) => {
    const parse = source => {
      const parsed = new DOMParser().parseFromString(source, "image/svg+xml");
      if (parsed.documentElement.localName !== "svg" || parsed.querySelector("parsererror")) throw new Error("Invalid brand SVG");
      return parsed.documentElement;
    };
    const root = parse(source);
    const greenGroup = root.querySelector('[id="Layer_4"]');
    if (greenGroup === null) throw new Error("Original green mark missing");
    const clean = node => {
      const copy = node.cloneNode(true);
      for (const element of [copy, ...copy.querySelectorAll("*")]) {
        if (!["svg", "g", "rect", "path"].includes(element.localName)) throw new Error("Unexpected SVG element");
        for (const attribute of [...element.attributes]) {
          if (["id", "data-name"].includes(attribute.name)) element.removeAttribute(attribute.name);
          else if (attribute.name === "style") {
            for (const declaration of attribute.value.split(";").filter(value => value.trim())) {
              const [name, value] = declaration.split(":").map(value => value.trim());
              if (!((name === "fill" && /^#[0-9a-f]{3,6}$/iu.test(value)) || (name === "fill-rule" && value === "evenodd"))) throw new Error("Unexpected SVG style");
              element.setAttribute(name, value);
            }
            element.removeAttribute("style");
          } else if (!["xmlns", "viewBox", "x", "y", "width", "height", "rx", "ry", "transform", "d"].includes(attribute.name)) throw new Error("Unexpected SVG attribute");
        }
      }
      return copy;
    };
    const full = clean(root);
    const icon = clean(root);
    icon.replaceChildren(clean(greenGroup));
    const fit = (svg, square) => {
      document.body.append(svg);
      const box = svg.getBBox();
      svg.remove();
      const padding = Math.max(box.width, box.height) * 0.07;
      let width = box.width + padding * 2, height = box.height + padding * 2;
      if (square) width = height = Math.max(width, height);
      svg.setAttribute("viewBox", [box.x + box.width / 2 - width / 2, box.y + box.height / 2 - height / 2, width, height].map(value => Number(value.toFixed(3))).join(" "));
      return new XMLSerializer().serializeToString(svg);
    };
    const logoSvg = fit(full, false), lightLogoSvg = fit(clean(parse(lightSource)), false), iconSvg = fit(icon, true);
    const pngs = {};
    for (const size of [16, 32, 48, 128]) {
      const image = new Image();
      await new Promise((resolve, reject) => {
        image.onload = resolve;
        image.onerror = () => reject(new Error("Brand rasterization failed"));
        image.src = `data:image/svg+xml,${encodeURIComponent(iconSvg)}`;
      });
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = size;
      canvas.getContext("2d").drawImage(image, 0, 0, size, size);
      pngs[size] = canvas.toDataURL("image/png").split(",")[1];
    }
    return { logoSvg, lightLogoSvg, iconSvg, pngs };
  }, { source, lightSource });
} finally { await browser.close(); }

const files = {};
const save = async (file, data) => {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, data);
  files[file] = createHash("sha256").update(data).digest("hex");
};
await save("apps/site/src/assets/brand-logo.svg", assets.lightLogoSvg + "\n");
await save("assets/branding/logo-light.svg", assets.lightLogoSvg + "\n");
await save("assets/branding/logo-dark.svg", assets.logoSvg + "\n");
await save("assets/branding/icon.svg", assets.iconSvg + "\n");
await save("apps/site/public/favicon.svg", assets.iconSvg + "\n");
const jsx = assets.logoSvg.replace("<svg ", '<svg className="panel-logo" aria-hidden="true" focusable="false" ').replaceAll("fill-rule=", "fillRule=");
await save("apps/extension/src/document-runtime/brand-logo.tsx", `// SPDX-License-Identifier: Apache-2.0\n// Generated by pnpm brand:generate from the owner's original SVG.\n\nexport function BrandLogo() {\n  return (\n${jsx.split("\n").map(line => "    " + line).join("\n")}\n  );\n}\n`);
for (const [size, png] of Object.entries(assets.pngs)) await save(`apps/extension/public/icons/icon-${size}.png`, Buffer.from(png, "base64"));
await writeFile("assets/branding/generated.json", JSON.stringify({ sourceSha256: createHash("sha256").update(source).digest("hex"), lightSourceSha256: createHash("sha256").update(lightSource).digest("hex"), files }, null, 2) + "\n");
console.log("Generated light/dark full logos, green mark, favicon and four transparent Chrome icons.");
